import type { DayPhase, ElementType, EggType, Pal, RegionId, SpawnLocation, WorkSuitability } from '../../types';

/**
 * Compact builder — keeps the dataset dense while staying fully typed.
 * stats: [HP, MeleeAtk, RangedAtk, Def, WorkSpeed]  (level-1 base stats)
 * partner: [name, description, cooldownSec]
 * skills: [skillId, levelLearned]
 * drops:  [itemId, chancePct]
 */
export const P = (
  id: string,
  dexNo: number,
  name: string,
  elements: ElementType[],
  egg: EggType,
  eggSize: Pal['eggSize'],
  breedingPower: number | null,
  stats: [number, number, number, number, number] | null,
  works: WorkSuitability[],
  partner: [string, string, number] | null,
  skills: [string, number][],
  drops: [string, number][],
  spawns: SpawnLocation[],
  extra: Partial<Pal> = {}
): Pal => ({
  id,
  dexNo,
  v10DexNo: null,
  name,
  title: '',
  elements,
  egg,
  eggSize,
  breedingPower,
  quality: 'complete',
  stats: stats ? { hp: stats[0], meleeAtk: stats[1], rangedAtk: stats[2], def: stats[3], workSpeed: stats[4] } : null,
  works,
  partnerSkill: partner ? { name: partner[0], description: partner[1], cooldownSec: partner[2] } : null,
  activeSkills: skills.map(([id, levelLearned]) => ({ id, levelLearned })),
  drops: drops.map(([itemId, chance]) => ({ itemId, chance })),
  spawns,
  lore: '',
  ...extra
});

export const sp = (region: RegionId, label: string, x: number, y: number, phase: DayPhase = 'both', alpha?: boolean, alphaLevel?: number): SpawnLocation => ({
  region,
  label,
  x,
  y,
  phase,
  isAlpha: alpha,
  alphaLevel
});

